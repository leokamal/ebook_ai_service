-- Replaces the Firebase "books" collection (book1, book2, ...).

create table if not exists public.books (
  id          bigint generated by default as identity primary key,  -- auto-increment (old book1 -> 1, book2 -> 2)
  title       text not null,
  file_name   text not null,                 -- file name inside the bucket's books/ folder
  url         text not null,                 -- storage path, e.g. 'books/flutter-succinctly.pdf'
  image_url   text,                          -- cover image path, e.g. 'images/flutter-succinctly.png'
  lang        text not null default 'en',    -- ISO language code (en, fr, ...)
  created_at  timestamptz not null default now()
);

create index if not exists books_lang_idx on public.books (lang);

-- Row Level Security: anyone can read the catalog; writes need the service_role key.
alter table public.books enable row level security;

drop policy if exists "books are publicly readable" on public.books;
create policy "books are publicly readable"
  on public.books for select
  using (true);

-- Private storage bucket used by the service (books/, images/, chroma_db/).
insert into storage.buckets (id, name, public)
values ('ebook-ai', 'ebook-ai', false)
on conflict (id) do nothing;

-- Seed data from the old Firebase documents.
insert into public.books (id, title, file_name, url, image_url, lang) values
  (1, 'flutter succinctly',
   'flutter-succinctly.pdf',
   'books/flutter-succinctly.pdf',
   'images/flutter-succinctly.png',
   'en'),
  (2, 'apprenez a creer votre site web avec html5 et css3',
   '13666-apprenez-a-creer-votre-site-web-avec-html5-et-css3.pdf',
   'books/13666-apprenez-a-creer-votre-site-web-avec-html5-et-css3.pdf',
   'images/apprenez a creer votre site web avec html5 et css3.png',
   'fr')
on conflict (id) do update set
  title = excluded.title,
  file_name = excluded.file_name,
  url = excluded.url,
  image_url = excluded.image_url,
  lang = excluded.lang;

-- Explicit ids don't advance the identity sequence; sync it so new inserts get 3, 4, ...
select setval(pg_get_serial_sequence('public.books', 'id'), (select max(id) from public.books));
